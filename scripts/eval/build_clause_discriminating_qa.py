#!/usr/bin/env python3
"""
Build a test set whose answers live in SUBORDINATE clauses — the missing instrument.

VERSION: v1.0
COMPATIBLE WITH: v2.3 store (`clauses` populated), whoosh_v2
DEPENDENCIES: duckdb, whoosh, klareco.parser
STAGE: Evaluation / test-set construction

Description:
    WHY THIS EXISTS — WE CANNOT MEASURE THE THING WE JUST BUILT.

    Measured across all 139 questions in the three existing test sets:

        answer in MAIN clause          135
        answer in SUBORDINATE clause     0        <- ZERO

    …while ~50% of their gold sentences ARE multi-clause. That is not chance. The
    sets were generated by extracting the MAIN CLAUSE's (subject, verb, object) —
    the very same flat shredding the reranker reads. **The test set is downstream
    of the component it is meant to evaluate** (failure mode F13, circularity), so
    it is structurally incapable of asking a question the flat schema cannot answer.

    Build a clause-aware reranker, measure it on those sets, and it will come back
    "identical to baseline" — and that will mean nothing at all.

    So: generate the questions from the SUBORDINATE clause instead. The answer then
    sits where a main-clause-only reranker CANNOT see it:

        "Ne klaras, ĉu UN transdonis la petskribon al Unesko…"
                        ^^^^^^^^^^^^^^^^^^ clause 1 — invisible to subj_radiko

    The material is there: 2,330,429 subordinate clauses (33.5% of all clauses),
    237,219 of them with a proper-noun subject and a verb.

    THE THREE GATES (docs/QA_TEST_SET_QUALITY_STANDARD.md is BINDING)

      R7  POSSIBLE     the gold sentence must rank in BM25's top-50 for the
                       question text alone. Otherwise it is a corpus-coverage gap,
                       not a ranking test.
      R16 NON-TRIVIAL  the gold sentence must NOT be at BM25 rank 1. The band
                       between "not rank 1" and "inside top 50" is the ONLY region
                       where reranking is observable.

                       R16 exists because `synthetic_who_rebuild_17` saturated at
                       recall@5 = 17/17, and all nine rerankers tied — a perfect
                       reranker could not have moved the number. R16 also names the
                       exact failure this set avoids: "Questions like `Kiu inventis
                       «Nonograms»?` hand BM25 a quoted title and are solved by
                       lexical overlap alone. A set made of them measures nothing."
                       Every existing capability set is made of them.

      NEW SUBORDINATE  the answer must be in clause_idx > 0. This is what makes the
                       set discriminate the CLAUSE TREE specifically, rather than
                       retrieval in general.

    R3 is honoured: the question uses the SOURCE VERB'S SURFACE FORM, taken from the
    AST, never a synthesized one.

Pipeline Position:
    clauses + whoosh --[THIS]--> data/test_sets/clause_discriminating_qa.jsonl
                             --> multi_reranker_bench.py

Usage:
    python scripts/eval/build_clause_discriminating_qa.py --n 60

Outputs:
    - data/test_sets/clause_discriminating_qa.jsonl
      {question, expected_answer, source_sentence_id, source_sentence_text,
       clause_idx, bm25_gold_rank, verb_surface, question_type}

Quality Checks:
    - REPORTS THE BM25 RANK HISTOGRAM. R16: "a set whose median gold rank is 1
      cannot measure ranking, no matter what its headline accuracy says."

Last Updated: 2026-07-14
Related Issues: #713, #736, #737, #778 (R16), #820
"""

from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

import duckdb
from whoosh import index as whoosh_index
from whoosh.qparser import OrGroup, QueryParser

from klareco.parser import expand_ast

DB = 'data/indexes/duckdb_store.db'
WHOOSH = 'data/indexes/whoosh_v2'


def _verb_surface(ast: dict, clause_idx: int) -> str | None:
    """R3: the SOURCE verb's surface form. Never synthesize one."""
    cl = (ast.get('propozicioj') or [])
    if clause_idx >= len(cl):
        return None
    v = cl[clause_idx].get('verbo')
    if not isinstance(v, dict):
        return None
    k = v.get('kerno', v)
    return k.get('plena_vorto') if isinstance(k, dict) else None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    ap.add_argument('--n', type=int, default=60, help='target question count')
    ap.add_argument('--pool', type=int, default=4000, help='candidate clauses to try')
    ap.add_argument('--top-k', type=int, default=50, help='R7: gold must rank <= this')
    ap.add_argument('--out', default='data/test_sets/clause_discriminating_qa.jsonl')
    args = ap.parse_args()

    con = duckdb.connect(DB, read_only=True)
    ix = whoosh_index.open_dir(WHOOSH)
    qp = QueryParser('text', ix.schema, group=OrGroup)

    print('  sampling SUBORDINATE clauses with a proper-noun subject…')
    # ⚠️ SAMPLE THE FILTERED SET, NOT THE RAW JOIN.
    #
    # `... WHERE ... USING SAMPLE 6000 ROWS` samples FIRST and filters after, so a
    # 6,000-row request returned 48 candidates. Wrap the filter in a subquery and
    # sample THAT.
    rows = con.execute(f"""
        SELECT * FROM (
            SELECT c.sid, c.clause_idx, c.subj_radiko, c.verb_radiko, c.obj_radiko,
                   s.text, s.ast_json
            FROM clauses c JOIN sentences s ON s.sid = c.sid
            WHERE c.clause_idx > 0
              AND c.subj_vortspeco = 'propra_nomo'
              AND c.verb_radiko IS NOT NULL
              AND c.obj_radiko  IS NOT NULL
              AND length(s.text) BETWEEN 50 AND 200
        ) USING SAMPLE {args.pool} ROWS (reservoir, 17)
    """).fetchall()
    print(f'  {len(rows):,} candidates\n')

    out: list[dict] = []
    drop = collections.Counter()
    ranks: list[int] = []

    with ix.searcher() as srch:
        for sid, ci, subj, verb, obj, text, aj in rows:
            if len(out) >= args.n:
                break
            try:
                ast = expand_ast(json.loads(aj))
            except Exception:
                drop['bad ast'] += 1
                continue

            surf = _verb_surface(ast, ci)          # R3
            if not surf:
                drop['no verb surface form (R3)'] += 1
                continue

            # R9: the answer must appear VERBATIM in the source.
            answer = None
            for w in (ast.get('vortoj') or []):
                if isinstance(w, dict) and (w.get('radiko') or '').lower() == (subj or '').lower():
                    answer = w.get('plena_vorto')
                    break
            if not answer or answer not in text:
                drop['answer not verbatim (R9)'] += 1
                continue

            # The OBJECT must be a real NOUN. R2 (the answer must be grammatically
            # governed) and R13 (Esperanto language quality).
            #
            # Without this the generator emits nonsense, because `obj_radiko` is
            # happily filled by a pronoun or a relative correlative:
            #
            #     "Kiu vundas ĝiaj?"          <- object is a POSSESSIVE
            #     "Kiu preteratentis kiun?"   <- object is the RELATIVE PRONOUN of
            #                                    the very clause we sampled
            #
            # Both are grammatical garbage, and a test set of them measures the
            # reranker's tolerance for garbage.
            objs = objw = None
            for w in (ast.get('vortoj') or []):
                if not isinstance(w, dict):
                    continue
                if (w.get('radiko') or '').lower() == (obj or '').lower():
                    objw = w
                    objs = w.get('plena_vorto')
                    break
            if not objs or not objw:
                drop['no object surface'] += 1
                continue
            if objw.get('vortspeco') not in ('substantivo', 'propra_nomo'):
                drop[f'object is not a NOUN (R2/R13)'] += 1
                continue

            question = f'Kiu {surf} {objs}?'

            # R1-ish: the answer must not be a function word or the object itself
            if answer.lower() == objs.lower() or len(answer) < 3:
                drop['degenerate'] += 1
                continue

            # ---- R7 (possible) + R16 (non-trivial) -----------------------
            hits = srch.search(qp.parse(question), limit=args.top_k)
            rank = next((i + 1 for i, h in enumerate(hits)
                         if int(h['id']) == sid), None)
            if rank is None:
                drop['gold NOT in BM25 top-50 (R7: impossible)'] += 1
                continue
            if rank == 1:
                drop['gold at BM25 rank 1 (R16: trivial)'] += 1
                continue

            ranks.append(rank)
            out.append({
                'id': f'clause-{sid}-{ci}',
                'question': question,
                'question_type': 'KIU',
                'expected_answer': answer,
                'expected_keywords': [answer],
                'source_sentence_id': str(sid),          # R8
                'source_sentence_text': text,
                'clause_idx': ci,                        # THE POINT OF THIS SET
                'verb_surface': surf,                    # R3
                'verb_root': verb,
                'object_radiko': obj,
                'bm25_gold_rank': rank,                  # R16 evidence
            })

    print(f'  {"reason dropped":42s} {"n":>5s}')
    for k, v in drop.most_common():
        print(f'  {k:42s} {v:5,}')

    if not out:
        print('\n  ✗ produced NOTHING. Loosen --pool or check the store.')
        return 1

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, 'w', encoding='utf-8') as f:
        for r in out:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')

    # R16: "Report, always: the BM25 rank distribution of the gold passage."
    hist = collections.Counter()
    for r in ranks:
        hist['2-5' if r <= 5 else ('6-10' if r <= 10 else
                                   ('11-25' if r <= 25 else '26-50'))] += 1
    ranks.sort()
    med = ranks[len(ranks) // 2]
    print(f'\n  ✓ {len(out)} questions -> {args.out}\n')
    print('  BM25 GOLD-RANK HISTOGRAM (R16 — a set whose median rank is 1')
    print('  cannot measure ranking, whatever its headline accuracy says):\n')
    for b in ('2-5', '6-10', '11-25', '26-50'):
        print(f'    rank {b:6s} {hist[b]:4}  {"█" * hist[b]}')
    print(f'\n    median gold rank : {med}   (R16 requires > 1)')
    print(f'    every answer is in a SUBORDINATE clause (clause_idx > 0)')
    print(f'    -> a main-clause-only reranker CANNOT see any of these answers.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
