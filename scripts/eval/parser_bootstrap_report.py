#!/usr/bin/env python3
"""Report parser metrics with sentence-level bootstrap confidence intervals.

The input is a reviewed plain-token CoNLL-U gold file. Parser predictions are
generated by the existing evaluator; each sentence remains the resampling unit
so long sentences do not masquerade as independent observations.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import random
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from scripts.eval import eval_conllu


def sentence_scores(path: Path) -> tuple[list[dict], dict]:
    diagnostics: list[dict] = []
    overall = eval_conllu.evaluate(str(path), diagnostics=diagnostics)
    by_sentence: dict[int, list[dict]] = {}
    for row in diagnostics:
        by_sentence.setdefault(int(row["sentence"]), []).append(row)
    gold = eval_conllu.read_gold(str(path))
    scores = []
    for number, sentence in enumerate(gold, 1):
        rows = by_sentence.get(number, [])
        rows = [row for row in rows if row["gold"]["upos"] != "PUNCT"]
        denominator = len(rows)
        scores.append({
            "tokens": denominator,
            "uas": sum(row["predicted"] is not None and "head" not in row["errors"]
                       for row in rows),
            "las": sum(row["predicted"] is not None
                       and not ({"head", "relation"} & set(row["errors"]))
                       for row in rows),
            "upos": sum(row["predicted"] is not None and "pos" not in row["errors"]
                        for row in rows),
        })
        # The evaluator's error list is token-scoped. POS errors do not affect
        # UAS/LAS, and relation errors do not affect UAS. Unaligned/crashed
        # tokens have no prediction and therefore score zero.
        for key in ("uas", "las", "upos"):
            scores[-1][key] = int(scores[-1][key])
    return scores, overall


def ratio(sample: list[dict], numerator: str) -> float:
    total = sum(row["tokens"] for row in sample)
    return sum(row[numerator] for row in sample) / total if total else 0.0


def bootstrap(scores: list[dict], seed: int, draws: int) -> dict:
    rng = random.Random(seed)
    output = {}
    for metric in ("uas", "las", "upos"):
        values = []
        for _ in range(draws):
            sample = [scores[rng.randrange(len(scores))] for _ in scores]
            values.append(ratio(sample, metric))
        values.sort()
        output[metric] = {
            "p025": values[int(draws * 0.025)],
            "p975": values[int(draws * 0.975) - 1],
        }
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("gold", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=20260906)
    parser.add_argument("--draws", type=int, default=2000)
    args = parser.parse_args()
    if args.draws < 100:
        parser.error("--draws must be at least 100")
    if not args.gold.is_file():
        parser.error(f"gold file not found: {args.gold}")
    scores, overall = sentence_scores(args.gold)
    if not scores or not any(row["tokens"] for row in scores):
        parser.error("gold file has no scored non-punctuation tokens")
    result = {
        "report_version": 1,
        "gold_sha256": hashlib.sha256(args.gold.read_bytes()).hexdigest(),
        "sentences": len(scores),
        "gold_tokens": sum(row["tokens"] for row in scores),
        "metrics": overall,
        "bootstrap": {
            "unit": "sentence",
            "seed": args.seed,
            "draws": args.draws,
            "confidence": 0.95,
            "intervals": bootstrap(scores, args.seed, args.draws),
        },
        "interpretation": "Intervals are sentence-bootstrap diagnostics; they do not correct annotation disagreement or establish genre coverage.",
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(result["bootstrap"], indent=2))


if __name__ == "__main__":
    main()
