#!/usr/bin/env python3
"""
Executable status — generate the "Current state" facts from the LIVE store (#887).

VERSION: v1.0
COMPATIBLE WITH: DuckDB store, Whoosh v2, current parser
DEPENDENCIES: duckdb, whoosh; klareco.parser
STAGE: Evaluation / Utility

Description:
    Docs went stale FOUR times in one 2026-07-18 audit (ontology "empty",
    entity_facts "missing", verb_klaso "0%", rerankers "tied" — all false). A
    doc claim that can be a query should BE a query. This emits the live facts
    (store rows, ontology edges by relation, entity_facts, artifacts present,
    parser sanity, index freshness) as a Markdown block + JSON, so DESIGN.md's
    "Current state" is generated, not remembered.

Usage:
    python scripts/validate/status_report.py                 # markdown to stdout
    python scripts/validate/status_report.py --json          # machine-readable
    python scripts/validate/status_report.py --write DESIGN.md  # replace the
        # block between <!--STATUS:BEGIN--> and <!--STATUS:END--> markers

Last Updated: 2026-07-19
Author: Claude Opus 4.8
Related Issues: #887, #838 (verify the rebuild), #817 (missing-artifact tracking)
See Also: DESIGN.md "Current state", klareco/preflight.py
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / 'data' / 'indexes' / 'duckdb_store.db'
WH = ROOT / 'data' / 'indexes' / 'whoosh_v2'

MARK_BEGIN = '<!--STATUS:BEGIN-->'
MARK_END = '<!--STATUS:END-->'


def _cols(con, table) -> list:
    try:
        return [r[0] for r in con.execute(f"DESCRIBE {table}").fetchall()]
    except Exception:
        return []


def _count(con, table) -> int:
    try:
        return con.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
    except Exception:
        return -1


def collect() -> dict:
    d = {'generated_utc': datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC'),
         'store_path': str(DB.relative_to(ROOT))}
    if not DB.exists():
        d['store_present'] = False
        return d
    d['store_present'] = True
    con = duckdb.connect(str(DB), read_only=True)

    d['sentences'] = _count(con, 'sentences')
    scols = _cols(con, 'sentences')
    d['sentences_has_verb_klaso'] = 'verb_klaso' in scols
    d['sentences_shredded_cols'] = [c for c in scols
                                    if c.endswith(('_radiko', '_vortspeco', '_kazo'))]

    d['ontology_nodes'] = _count(con, 'ontology_nodes')
    d['ontology_edges'] = _count(con, 'ontology_edges')
    d['ontology_edges_by_rel'] = {}
    try:
        for rel, nn in con.execute(
                "SELECT rel, count(*) FROM ontology_edges GROUP BY rel").fetchall():
            d['ontology_edges_by_rel'][rel] = nn
    except Exception:
        pass

    tbls = {r[0] for r in con.execute(
        "SELECT table_name FROM information_schema.tables").fetchall()}
    d['entity_facts_present'] = 'entity_facts' in tbls
    d['entity_facts_rows'] = _count(con, 'entity_facts') if d['entity_facts_present'] else 0
    con.close()

    # Whoosh index
    try:
        from whoosh import index as widx
        d['whoosh_present'] = widx.exists_in(str(WH))
        d['whoosh_docs'] = widx.open_dir(str(WH)).doc_count() if d['whoosh_present'] else 0
    except Exception:
        d['whoosh_present'] = WH.exists()
        d['whoosh_docs'] = None

    # Parser-data artifacts
    art = ROOT / 'data'
    d['protected_roots_present'] = (art / 'vocabularies' / 'protected_roots.json').exists()
    d['proper_nouns_v3_present'] = (art / 'proper_nouns_dynamic_v3.json').exists()

    # Parser sanity: the canary that was wrong for a month
    try:
        from klareco.parser import parse
        ast = parse("Zamenhof kreis Esperanton.")
        for w in ast.get('objekto', {}).get('kerno', {}) or {}:
            pass
        obj = (ast.get('objekto') or {}).get('kerno') or {}
        d['esperanton_radiko'] = obj.get('radiko')
        d['esperanton_ok'] = obj.get('radiko') == 'esperant'
    except Exception as e:
        d['esperanton_radiko'] = f'ERROR: {e}'
        d['esperanton_ok'] = False
    return d


def render_md(d: dict) -> str:
    if not d.get('store_present'):
        return f"{MARK_BEGIN}\n**Store MISSING** at `{d['store_path']}` (generated {d['generated_utc']}).\n{MARK_END}"
    ok = lambda b: '✅' if b else '⚠️'
    rel = ', '.join(f"{k} {v:,}" for k, v in sorted(
        d.get('ontology_edges_by_rel', {}).items(), key=lambda x: -x[1]))
    lines = [
        MARK_BEGIN,
        f"<!-- generated by scripts/validate/status_report.py — do not hand-edit -->",
        f"**Current state (generated {d['generated_utc']})**",
        "",
        "| Fact | Live value |",
        "|---|---|",
        f"| Store | ✅ {d['sentences']:,} sentences (`{d['store_path']}`) |",
        f"| Shredded AST columns | {', '.join(d['sentences_shredded_cols'])} |",
        f"| `verb_klaso` column | {ok(d['sentences_has_verb_klaso'])} {'present' if d['sentences_has_verb_klaso'] else 'NOT built (membership is in ontology_edges) — #875'} |",
        f"| Ontology | {ok(d['ontology_edges']>0)} {d['ontology_nodes']:,} nodes / {d['ontology_edges']:,} edges ({rel}) |",
        f"| `entity_facts` | {ok(d['entity_facts_present'])} {'present, '+format(d['entity_facts_rows'],',')+' rows' if d['entity_facts_present'] else 'MISSING'} |",
        (f"| Whoosh index | {ok(bool(d.get('whoosh_present')))} {d['whoosh_docs']:,} docs |"
         if isinstance(d.get('whoosh_docs'), int)
         else f"| Whoosh index | {ok(bool(d.get('whoosh_present')))} present |"),
        f"| Parser canary | {ok(d['esperanton_ok'])} `Esperanton` → radiko `{d['esperanton_radiko']}` (want `esperant`) |",
        f"| `protected_roots.json` | {ok(d['protected_roots_present'])} {'present' if d['protected_roots_present'] else 'missing'} |",
        f"| `proper_nouns_dynamic_v3` | {ok(d['proper_nouns_v3_present'])} {'present' if d['proper_nouns_v3_present'] else 'missing (capitalization fallback)'} |",
        MARK_END,
    ]
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--json', action='store_true')
    ap.add_argument('--write', help='embed the block between STATUS markers in this file')
    a = ap.parse_args()
    d = collect()
    if a.json:
        print(json.dumps(d, ensure_ascii=False, indent=2)); return
    block = render_md(d)
    if a.write:
        p = Path(a.write); txt = p.read_text()
        if MARK_BEGIN in txt and MARK_END in txt:
            pre = txt[:txt.index(MARK_BEGIN)]; post = txt[txt.index(MARK_END)+len(MARK_END):]
            p.write_text(pre + block + post)
            print(f"updated STATUS block in {a.write}")
        else:
            print(f"no STATUS markers in {a.write}; add {MARK_BEGIN} / {MARK_END}", file=sys.stderr)
            sys.exit(1)
    else:
        print(block)


if __name__ == '__main__':
    main()
